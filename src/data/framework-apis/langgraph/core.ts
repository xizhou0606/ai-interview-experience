const STORE = 'https://reference.langchain.com/python/langgraph.store'
const PREBUILT = 'https://reference.langchain.com/python/langgraph.prebuilt'

type LangGraphApiInput = Omit<FrameworkApiReference, 'slug' | 'technologySlug' | 'maturity' | 'exampleLanguage'> & {
  slug: string
  maturity?: FrameworkApiReference['maturity']
}

function langGraphApi(input: LangGraphApiInput): FrameworkApiReference {
  const learningMeta = langGraphLearningMeta[input.name as keyof typeof langGraphLearningMeta]
  if (!learningMeta) throw new Error(`Missing structured LangGraph learning metadata for ${input.name}`)
  return {
    ...input,
    ...learningMeta,
    slug: `langgraph-${input.slug}`,
    technologySlug: 'langgraph',
    maturity: input.maturity ?? 'stable',
    exampleLanguage: 'py',
  }
}

